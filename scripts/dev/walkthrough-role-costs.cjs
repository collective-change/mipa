const { chromium } = require("playwright");
const S = require("path").join(__dirname, "shots");
require("fs").mkdirSync(S, { recursive: true });
const shot = async (page, name) => { await page.waitForTimeout(1000); await page.screenshot({ path: `${S}/${name}.png` }); };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, locale: process.argv[3] || "en-US" });
  const page = await ctx.newPage();
  const log = [];
  page.on("pageerror", e => log.push("pageerror: " + e.message));
  page.on("console", m => { if (m.type() == "error") log.push("error: " + m.text().slice(0, 200)); });
  await page.goto("http://localhost:9000/auth", { waitUntil: "networkidle" });
  const panel = page.getByRole("tabpanel").first();
  await panel.locator("input[type=email]").fill(process.argv[2]);
  await panel.locator("input[type=password]").fill("correct-horse-42");
  await panel.locator("button").filter({ hasText: /sign in|登入/i }).first().click();
  await page.waitForURL(u => !u.pathname.startsWith("/auth"));
  await page.waitForTimeout(2000);
  await page.getByRole("button", { name: /sample|範例/i }).first().click();
  await page.waitForURL(u => u.pathname.includes("/model/"), { timeout: 20000 });
  await page.waitForTimeout(3000);
  await page.getByRole("button", { name: /^calculate$|^計算$/i }).first().click();
  await page.waitForTimeout(5000);
  const p = new URL(page.url()).pathname;
  const orgPath = p.split("/model/")[0], orgId = p.split("/model/")[1].split("/")[0];
  await page.goto(`http://localhost:9000${orgPath}/ideate/actions/${orgId}`, { waitUntil: "load" });
  await page.waitForTimeout(4000);
  await page.getByText(/supermarkets|超市/).first().click();
  await page.waitForTimeout(3000);
  const sel = page.locator(".q-field").filter({ hasText: /Effort cost per hour|每小時/ }).first();
  await sel.scrollIntoViewIfNeeded();
  console.log("SELECTED:", (await sel.innerText()).replace(/\n/g, " | "));
  await sel.click();
  await page.waitForTimeout(800);
  console.log("OPTIONS:", (await page.getByRole("listbox").innerText()).replace(/\n/g, " | "));
  await shot(page, "role-1-menu");
  await page.getByText(/Add a role or person|新增角色/).last().click();
  await page.waitForTimeout(800);
  await page.getByLabel(/Role or person|角色或人員/).fill("Doctor");
  await page.getByLabel(/Cost per hour|每小時成本/).fill("80");
  await shot(page, "role-2-dialog");
  await page.getByRole("dialog").getByRole("button", { name: /^add$|^新增$/i }).click();
  await page.waitForTimeout(2500);
  console.log("AFTER ADD:", (await sel.innerText()).replace(/\n/g, " | "));
  await shot(page, "role-3-after");
  console.log("LOG:\n" + log.join("\n"));
  await browser.close();
})();
