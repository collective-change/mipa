const { chromium } = require("playwright");
const S = require("path").join(__dirname, "shots");
require("fs").mkdirSync(S, { recursive: true });
const shot = async (page, name) => { await page.waitForTimeout(800); await page.screenshot({ path: `${S}/${name}.png` }); };
const step = m => console.log("STEP", m);
(async () => {
  const email = process.argv[2];
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 950 }, locale: process.argv[3] || "en-US" });
  const page = await ctx.newPage();
  const log = [];
  page.on("pageerror", e => log.push("pageerror: " + e.message));
  page.on("console", m => { if (m.type() == "error") log.push("error: " + m.text().slice(0, 300)); });
  try {
    await page.goto("http://localhost:9000/auth", { waitUntil: "networkidle" });
    const panel = page.getByRole("tabpanel").first();
    await panel.locator("input[type=email]").fill(email);
    await panel.locator("input[type=password]").fill("correct-horse-42");
    await panel.locator("button").filter({ hasText: /sign in|登入/i }).first().click();
    await page.waitForURL(u => !u.pathname.startsWith("/auth"));
    await page.waitForTimeout(2000);
    step("add org");
    await page.getByRole("button", { name: /add organization|新增組織/i }).first().click();
    await page.getByLabel("Name").fill("Corner Bakery");
    await page.getByLabel("Goal").fill("Good bread for the neighbourhood");
    await page.getByLabel("Currency").click();
    await page.getByRole("option", { name: "USD", exact: true }).click();
    await page.getByRole("button", { name: /save/i }).click();
    await page.waitForTimeout(4000);
    await page.locator(".q-card a").first().click();
    await page.waitForURL(u => u.pathname.includes("/model/"));
    await page.waitForTimeout(4000);
    const modelUrl = page.url();
    await shot(page, "ai-1-model-invite");
    step("draft without provider");
    await page.getByRole("button", { name: /draft with ai/i }).first().click();
    await page.waitForTimeout(1500);
    await shot(page, "ai-2-no-provider");
    await page.getByRole("link", { name: /open ai settings/i }).click().catch(() => page.getByText(/open ai settings/i).click());
    await page.waitForURL(u => u.pathname.includes("/organization/ai/"));
    await page.waitForTimeout(2000);
    step("connect provider");
    await page.getByText("OpenAI-compatible endpoint").click();
    await page.getByLabel("Endpoint address").fill("http://127.0.0.1:8787/v1");
    await page.getByLabel("Model").fill("mock-model");
    await page.getByLabel("API key").fill("sk-test-secret-1234");
    await page.getByRole("button", { name: /test and save/i }).click();
    await page.waitForTimeout(4000);
    await shot(page, "ai-3-settings");
    console.log("STATUS:", (await page.locator(".q-card").nth(1).innerText()).split("\n").slice(0, 3).join(" | "));
    step("draft");
    await page.goto(modelUrl, { waitUntil: "load" });
    await page.waitForTimeout(3000);
    await page.getByRole("button", { name: /draft with ai/i }).first().click();
    await page.waitForTimeout(1500);
    await page.locator(".draft-dialog textarea").fill("We are a small bakery with 4 staff. We sell bread in our shop. Our biggest costs are flour, energy and wages.");
    await shot(page, "ai-4-describe");
    await page.getByRole("button", { name: /draft my model/i }).click();
    await page.getByText("Do you also sell to cafés?").waitFor({ timeout: 30000 });
    await shot(page, "ai-5-questions");
    await page.locator(".draft-dialog textarea").first().fill("No, only in our shop.");
    await page.getByRole("button", { name: /^answer$/i }).click();
    step("waiting for repaired draft");
    await page.getByText("The draft calculates without errors.").waitFor({ timeout: 60000 });
    await shot(page, "ai-6-preview");
    step("ask for changes");
    await page.getByLabel("Ask for changes").fill("Please add solar panels.");
    await page.locator(".draft-dialog .q-field__after button").click();
    await page.getByText("energy saved by solar panels", { exact: true }).waitFor({ timeout: 60000 });
    await page.getByText("The draft calculates without errors.").waitFor({ timeout: 60000 });
    await shot(page, "ai-7-preview-solar");
    const addBtn = page.getByRole("button", { name: /add \d+ factors to the model/i });
    console.log("ADD BUTTON:", await addBtn.innerText());
    await addBtn.click();
    await page.waitForTimeout(6000);
    await shot(page, "ai-8-added");
    step("remove");
    await page.getByRole("button", { name: /remove ai draft/i }).click();
    await page.waitForTimeout(800);
    console.log("CONFIRM:", (await page.getByRole("dialog").innerText()).replace(/\n+/g, " | "));
    await page.getByRole("dialog").getByRole("button", { name: /ok/i }).click();
    await page.waitForTimeout(3000);
    await shot(page, "ai-9-removed");
  } catch (e) {
    console.log("FAILED:", e.message.split("\n")[0]);
    await shot(page, "ai-fail");
  }
  console.log("LOG:\n" + log.join("\n"));
  await browser.close();
})();
