const { chromium } = require("playwright");
const S = require("path").join(__dirname, "shots");
require("fs").mkdirSync(S, { recursive: true });
const shot = async (page, name) => { await page.waitForTimeout(1200); await page.screenshot({ path: `${S}/${name}.png` }); };
(async () => {
  const lang = process.argv[2] || "en-US";
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: lang });
  const page = await ctx.newPage();
  const log = [];
  page.on("console", m => { if (["error"].includes(m.type())) log.push(m.type() + ": " + m.text().slice(0, 300)); });
  page.on("pageerror", e => log.push("pageerror: " + e.message));
  await page.goto("http://localhost:9000/auth", { waitUntil: "networkidle" });
  const panel = page.getByRole("tabpanel").first();
  await panel.locator("input[type=email]").fill(process.argv[3] || "sam@example.org");
  await panel.locator("input[type=password]").fill("correct-horse-42");
  await panel.locator("button[type=submit], button").filter({ hasText: /sign in|登入/i }).first().click();
  await page.waitForURL(u => !u.pathname.startsWith("/auth"));
  await page.waitForTimeout(2500);
  await shot(page, `s-${lang}-1-dash`);
  await page.getByRole("button", { name: /sample|範例/i }).first().click();
  await page.waitForURL(u => u.pathname.includes("/model/"), { timeout: 20000 });
  await page.waitForTimeout(4000);
  await shot(page, `s-${lang}-2-model`);
  await page.getByRole("button", { name: /^calculate$|^計算$/i }).first().click().catch(e => log.push("no calc btn " + e.message.slice(0,100)));
  await page.waitForTimeout(6000);
  await shot(page, `s-${lang}-3-calculated`);
  const orgPath = new URL(page.url()).pathname.split("/model/")[0];
  const orgId = new URL(page.url()).pathname.split("/model/")[1].split("/")[0];
  await page.goto(`http://localhost:9000${orgPath}/ideate/actions/${orgId}`, { waitUntil: "load" });
  await page.waitForTimeout(4000);
  await page.getByRole("button", { name: /recalculate|重新計算/i }).first().click();
  await page.waitForTimeout(12000);
  await shot(page, `s-${lang}-4-actions`);
  console.log((await page.locator("table").first().innerText()).replace(/\n+/g, " | ").slice(0, 1200));
  console.log("LOG:\n" + log.join("\n"));
  await browser.close();
})();
